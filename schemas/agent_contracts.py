"""
schemas.agent_contracts — Structured Data Contracts for Vibe UI Swarm Agents

Defines formal, typed, JSON-serializable contracts between autonomous swarm stations:
1. ConceptContract (vibe-concept-architect -> swarm)
2. TrendEvidence (vibe-trend-hunter -> swarm)
3. DesignGenomeContract (vibe-art-director -> vibe-master-builder)
4. UIArtifactContract (vibe-master-builder -> auditors)
5. EvaluationReportContract (vibe-tech-auditor & vibe-visual-auditor -> host agent)

Each contract provides `.to_dict()`, `.from_dict()`, `.validate()`, and JSON helpers.
"""

from dataclasses import dataclass, field, asdict
from typing import Dict, Any, List, Optional, Tuple, Union
import json


def _parse_strict_bool(val: Any, default: bool = False) -> bool:
    """Strict boolean parser preventing bool('false') == True bug."""
    if val is None:
        return default
    if val is True or val is False:
        return val
    if isinstance(val, (int, float)):
        return bool(val)
    if isinstance(val, str):
        val_clean = val.strip().lower()
        if val_clean in ("true", "1", "yes", "pass", "passed", "ok"):
            return True
        if val_clean in ("false", "0", "no", "fail", "failed"):
            return False
    return default


@dataclass
class ConceptContract:
    """Macro Concept Manifest generated by vibe-concept-architect."""
    domain: str
    product_name: str
    target_audience: str
    emotional_tone: Union[str, List[str]]
    primary_job_to_be_done: str
    spatial_flow: List[str]
    language: str = "en"
    is_rtl: bool = False
    metadata: Dict[str, Any] = field(default_factory=dict)

    @property
    def emotional_tones(self) -> List[str]:
        """Normalize emotional_tone to a list of tone strings."""
        if isinstance(self.emotional_tone, (list, tuple)):
            return [str(t).strip() for t in self.emotional_tone if str(t).strip()]
        if isinstance(self.emotional_tone, str):
            return [t.strip() for t in self.emotional_tone.split(",") if t.strip()]
        return []

    @property
    def emotional_tone_str(self) -> str:
        """Normalize emotional_tone to a comma-separated string."""
        if isinstance(self.emotional_tone, (list, tuple)):
            return ", ".join(str(t).strip() for t in self.emotional_tone if str(t).strip())
        return str(self.emotional_tone or "")

    def validate(self) -> Tuple[bool, List[str]]:
        errors = []
        if not self.domain or not isinstance(self.domain, str):
            errors.append("domain must be a non-empty string")
        if not self.product_name or not isinstance(self.product_name, str):
            errors.append("product_name must be a non-empty string")
        if not self.target_audience or not isinstance(self.target_audience, str):
            errors.append("target_audience must be a non-empty string")
        if not self.emotional_tone:
            errors.append("emotional_tone must be a non-empty string or list of strings")
        elif isinstance(self.emotional_tone, str):
            if not self.emotional_tone.strip():
                errors.append("emotional_tone must be a non-empty string")
        elif isinstance(self.emotional_tone, (list, tuple)):
            if len(self.emotional_tone) == 0:
                errors.append("emotional_tone list must not be empty")
            elif not all(isinstance(t, str) and t.strip() for t in self.emotional_tone):
                errors.append("emotional_tone list items must be non-empty strings")
        else:
            errors.append("emotional_tone must be a string or list of strings")
        if not self.primary_job_to_be_done or not isinstance(self.primary_job_to_be_done, str):
            errors.append("primary_job_to_be_done must be a non-empty string")
        if not isinstance(self.spatial_flow, (list, tuple)) or len(self.spatial_flow) == 0:
            errors.append("spatial_flow must be a non-empty list of section identifiers")
        return len(errors) == 0, errors

    @property
    def blueprint(self) -> Dict[str, Any]:
        return self.metadata.get("blueprint", {})

    @property
    def product_mode(self) -> str:
        return self.metadata.get("product_mode", "persuade")

    @property
    def visual_energy(self) -> str:
        return self.metadata.get("visual_energy", "balanced")

    def to_dict(self) -> Dict[str, Any]:
        d = asdict(self)
        if self.metadata:
            for k in ("blueprint", "product_mode", "visual_energy", "audience", "confidence"):
                if k in self.metadata and k not in d:
                    d[k] = self.metadata[k]
        return d

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "ConceptContract":
        raw_tone = data.get("emotional_tone", "")
        if isinstance(raw_tone, (list, tuple)):
            normalized_tone: Union[str, List[str]] = [str(t).strip() for t in raw_tone if str(t).strip()]
        elif isinstance(raw_tone, str):
            normalized_tone = raw_tone.strip()
        else:
            normalized_tone = str(raw_tone)

        return cls(
            domain=data.get("domain", ""),
            product_name=data.get("product_name", ""),
            target_audience=data.get("target_audience", ""),
            emotional_tone=normalized_tone,
            primary_job_to_be_done=data.get("primary_job_to_be_done", ""),
            spatial_flow=list(data.get("spatial_flow", [])),
            language=data.get("language", "en"),
            is_rtl=_parse_strict_bool(data.get("is_rtl", False)),
            metadata=dict(data.get("metadata", {}))
        )

    def to_json(self, indent: int = 2) -> str:
        return json.dumps(self.to_dict(), ensure_ascii=False, indent=indent)

    @classmethod
    def from_json(cls, json_str: str) -> "ConceptContract":
        return cls.from_dict(json.loads(json_str))


@dataclass
class TrendEvidence:
    """Trend Research & Visual Chemistry Evidence produced by vibe-trend-hunter."""
    selected_style: str
    style_reasoning: str
    composition_archetype: str
    typography_pair: Union[Dict[str, str], Tuple[str, str], List[str]]
    novelty_risk_assessment: str
    banned_slop_tropes: List[str]
    trend_sources: List[str] = field(default_factory=list)
    confidence: float = 0.90

    def __post_init__(self):
        # Auto-convert tuple/list (display, body) to dict {"display": ..., "body": ...}
        if isinstance(self.typography_pair, (tuple, list)):
            if len(self.typography_pair) >= 2:
                self.typography_pair = {
                    "display": str(self.typography_pair[0]),
                    "body": str(self.typography_pair[1])
                }
            elif len(self.typography_pair) == 1:
                self.typography_pair = {
                    "display": str(self.typography_pair[0]),
                    "body": str(self.typography_pair[0])
                }
            else:
                self.typography_pair = {}

    def validate(self) -> Tuple[bool, List[str]]:
        errors = []
        if not self.selected_style:
            errors.append("selected_style must be specified")
        if not self.style_reasoning:
            errors.append("style_reasoning must not be empty")
        if not self.composition_archetype:
            errors.append("composition_archetype must be specified")
        if isinstance(self.typography_pair, dict):
            if self.typography_pair and not any(str(v).strip() for v in self.typography_pair.values()):
                errors.append("typography_pair values must contain at least one non-empty font name when supplied")
        elif isinstance(self.typography_pair, (tuple, list)):
            if len(self.typography_pair) < 2 or not str(self.typography_pair[0]).strip() or not str(self.typography_pair[1]).strip():
                errors.append("typography_pair tuple must contain at least (display, body)")
        else:
            errors.append("typography_pair must be a dictionary or tuple of (display, body)")
        if not self.novelty_risk_assessment:
            errors.append("novelty_risk_assessment must not be empty")
        if not isinstance(self.banned_slop_tropes, (list, tuple)):
            errors.append("banned_slop_tropes must be a list of prohibited anti-patterns")
        return len(errors) == 0, errors

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "TrendEvidence":
        raw_typo = data.get("typography_pair", {})
        if isinstance(raw_typo, (tuple, list)) and len(raw_typo) >= 2:
            typo_dict = {"display": str(raw_typo[0]), "body": str(raw_typo[1])}
        elif isinstance(raw_typo, dict):
            typo_dict = dict(raw_typo)
        else:
            typo_dict = {}

        return cls(
            selected_style=data.get("selected_style", "clean_stripe"),
            style_reasoning=data.get("style_reasoning", ""),
            composition_archetype=data.get("composition_archetype", "classic_structured_saas"),
            typography_pair=typo_dict,
            novelty_risk_assessment=data.get("novelty_risk_assessment", ""),
            banned_slop_tropes=list(data.get("banned_slop_tropes", [])),
            trend_sources=list(data.get("trend_sources", [])),
            confidence=float(data.get("confidence", 0.90))
        )

    def to_json(self, indent: int = 2) -> str:
        return json.dumps(self.to_dict(), ensure_ascii=False, indent=indent)

    @classmethod
    def from_json(cls, json_str: str) -> "TrendEvidence":
        return cls.from_dict(json.loads(json_str))


@dataclass
class DesignGenomeContract:
    """Binding Design Style Blueprint & Token Genome curated by vibe-art-director."""
    tokens: Dict[str, Any]
    geometry: Dict[str, Any]
    density: str
    surfaces: Dict[str, Any]
    motion_profile: Dict[str, Any]
    domain: str = ""
    style: str = "clean_stripe"
    # Unified Design Genome 2.0 extensions
    typography: Dict[str, Any] = field(default_factory=dict)
    composition_archetype: str = "classic_structured_saas"
    style_family: str = ""
    style_id: str = ""
    palette: Dict[str, Any] = field(default_factory=dict)
    decision_trace: Dict[str, Any] = field(default_factory=dict)
    genome: Dict[str, Any] = field(default_factory=dict)
    selected_style: str = ""
    composite_score: float = 90.0
    intent: Dict[str, Any] = field(default_factory=dict)

    def get(self, key: str, default: Any = None) -> Any:
        return getattr(self, key, default)

    def __getitem__(self, key: str) -> Any:
        return getattr(self, key)

    def __contains__(self, key: str) -> bool:
        return hasattr(self, key)

    def validate(self) -> Tuple[bool, List[str]]:
        errors = []
        if not isinstance(self.tokens, dict) or not self.tokens:
            errors.append("tokens must be a non-empty dictionary containing OKLCH color values")
        if not isinstance(self.geometry, dict) or not self.geometry:
            errors.append("geometry must define container radiuses and border treatments")
        if self.density not in ("compact", "balanced", "airy"):
            errors.append("density must be one of: 'compact', 'balanced', 'airy'")
        if not isinstance(self.surfaces, dict):
            errors.append("surfaces must be a dictionary specifying depth and elevation")
        if not isinstance(self.motion_profile, dict):
            errors.append("motion_profile must specify spring parameters or timing curves")
        return len(errors) == 0, errors

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "DesignGenomeContract":
        raw_surfaces = data.get("surfaces", {})
        if isinstance(raw_surfaces, str):
            surfaces_dict = {"depth": raw_surfaces, "elevation": "surface"}
        elif isinstance(raw_surfaces, dict):
            surfaces_dict = dict(raw_surfaces)
        else:
            surfaces_dict = {"depth": "flat", "elevation": "surface"}

        style_val = data.get("style") or data.get("selected_style") or "clean_stripe"
        raw_density = str(data.get("density", "balanced"))
        if raw_density not in ("compact", "balanced", "airy"):
            raw_density = "compact" if any(k in raw_density.lower() for k in ["dense", "high", "hud"]) else ("airy" if "airy" in raw_density.lower() else "balanced")

        return cls(
            tokens=dict(data.get("tokens", {})),
            geometry=dict(data.get("geometry", {})),
            density=raw_density,
            surfaces=surfaces_dict,
            motion_profile=dict(data.get("motion_profile", {})),
            domain=str(data.get("domain", "")),
            style=str(style_val),
            typography=dict(data.get("typography", {})),
            composition_archetype=str(data.get("composition_archetype", "classic_structured_saas")),
            style_family=str(data.get("style_family", "")),
            style_id=str(data.get("style_id", style_val)),
            palette=dict(data.get("palette", {})),
            decision_trace=dict(data.get("decision_trace", {})),
            genome=dict(data.get("genome", {})),
            selected_style=str(data.get("selected_style", style_val)),
            composite_score=float(data.get("composite_score", 90.0)),
            intent=dict(data.get("intent", {}))
        )

    def to_json(self, indent: int = 2) -> str:
        return json.dumps(self.to_dict(), ensure_ascii=False, indent=indent)

    @classmethod
    def from_json(cls, json_str: str) -> "DesignGenomeContract":
        return cls.from_dict(json.loads(json_str))


@dataclass
class UIArtifactContract:
    """Engineered UI Output delivered by vibe-master-builder."""
    code_html_or_tsx: str
    title: str
    signature_widgets: List[Dict[str, Any]]
    micro_interactions: List[Dict[str, Any]]
    viewport_configs: List[Dict[str, Any]]
    format: str = "html"
    brand_name: str = "Vibe Studio"
    component_name: str = "GeneratedMasterpiece"

    def validate(self) -> Tuple[bool, List[str]]:
        errors = []
        if not self.code_html_or_tsx or not isinstance(self.code_html_or_tsx, str):
            errors.append("code_html_or_tsx must contain executable markup or code")
        if not self.title or not isinstance(self.title, str):
            errors.append("title must be specified")
        if not isinstance(self.signature_widgets, (list, tuple)):
            errors.append("signature_widgets must be a list of widget specifications")
        if not isinstance(self.micro_interactions, (list, tuple)):
            errors.append("micro_interactions must be a list of interaction definitions")
        if not isinstance(self.viewport_configs, (list, tuple)) or len(self.viewport_configs) == 0:
            errors.append("viewport_configs must list tested viewports (e.g. 390px, 768px, 1440px)")
        if self.format not in ("html", "tsx", "jsx"):
            errors.append("format must be 'html', 'tsx', or 'jsx'")
        return len(errors) == 0, errors

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "UIArtifactContract":
        return cls(
            code_html_or_tsx=data.get("code_html_or_tsx", ""),
            title=data.get("title", ""),
            signature_widgets=list(data.get("signature_widgets", [])),
            micro_interactions=list(data.get("micro_interactions", [])),
            viewport_configs=list(data.get("viewport_configs", [])),
            format=data.get("format", "html"),
            brand_name=data.get("brand_name", "Vibe Studio"),
            component_name=data.get("component_name", "GeneratedMasterpiece")
        )

    def to_json(self, indent: int = 2) -> str:
        return json.dumps(self.to_dict(), ensure_ascii=False, indent=indent)

    @classmethod
    def from_json(cls, json_str: str) -> "UIArtifactContract":
        return cls.from_dict(json.loads(json_str))


@dataclass
class EvaluationReportContract:
    """Comprehensive Quality Audit Report issued by Adversarial Technical & Visual Auditors."""
    hard_quality_pass: bool = False
    wcag_contrast_score: float = 0.0
    overflow_0px_pass: bool = False
    aesthetic_quality_score: float = 0.0
    slop_penalty_deductions: float = 0.0
    correction_advice: List[str] = field(default_factory=list)
    iteration: int = 1
    acceptance_status: str = "PENDING"
    detailed_checks: List[Dict[str, Any]] = field(default_factory=list)
    wcag_contrast_status: str = "NOT_EVALUATED"
    overflow_status: str = "NOT_EVALUATED"
    screenshot_status: str = "NOT_EVALUATED"
    critic_status: str = "NOT_EVALUATED"
    runtime_mode: str = "static"

    def validate(self) -> Tuple[bool, List[str]]:
        errors = []
        if not isinstance(self.hard_quality_pass, bool):
            errors.append("hard_quality_pass must be a boolean")
        if not (0.0 <= self.wcag_contrast_score <= 21.5):
            errors.append("wcag_contrast_score must be a float between 0.0 and 21.0")
        if not isinstance(self.overflow_0px_pass, bool):
            errors.append("overflow_0px_pass must be a boolean asserting 0px mobile overflow")
        if not (0.0 <= self.aesthetic_quality_score <= 100.0):
            errors.append("aesthetic_quality_score must be between 0.0 and 100.0")
        if self.slop_penalty_deductions < 0.0:
            errors.append("slop_penalty_deductions cannot be negative")
        if not isinstance(self.correction_advice, (list, tuple)):
            errors.append("correction_advice must be a list of actionable guidance strings")

        status_values = {"PASS", "FAIL", "NOT_EVALUATED"}
        for field_name in ("wcag_contrast_status", "overflow_status", "screenshot_status"):
            if getattr(self, field_name) not in status_values:
                errors.append(f"{field_name} must be one of {sorted(status_values)}")
        if self.critic_status not in {"ACCEPTED", "REJECTED", "NOT_EVALUATED"}:
            errors.append("critic_status must be ACCEPTED, REJECTED, or NOT_EVALUATED")
        if not isinstance(self.runtime_mode, str) or not self.runtime_mode.strip():
            errors.append("runtime_mode must be a non-empty string")
        if self.overflow_status == "PASS" and self.overflow_0px_pass is not True:
            errors.append("overflow_status=PASS requires overflow_0px_pass=True")
        if self.overflow_status != "PASS" and self.overflow_0px_pass is True:
            errors.append("overflow_0px_pass=True requires overflow_status=PASS")
        if self.hard_quality_pass and any(
            status == "FAIL"
            for status in (self.wcag_contrast_status, self.overflow_status, self.screenshot_status)
        ):
            errors.append("hard_quality_pass cannot be True when an evidence gate is FAIL")
        return len(errors) == 0, errors

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "EvaluationReportContract":
        raw_pass = data.get("hard_quality_pass")
        # Strict boolean parsing: do not allow bool("false") to become True
        hard_pass = (raw_pass is True or str(raw_pass).strip().lower() == "true") if raw_pass is not None else False

        raw_overflow = data.get("overflow_0px_pass")
        overflow_pass = (raw_overflow is True or str(raw_overflow).strip().lower() == "true") if raw_overflow is not None else False

        # Fail-closed default: acceptance_status="PENDING" if not explicitly set to passed
        raw_status = data.get("acceptance_status")
        if raw_status is not None and str(raw_status).strip():
            acceptance_status = str(raw_status).strip()
        else:
            acceptance_status = "ACCEPTED" if hard_pass else "PENDING"

        return cls(
            hard_quality_pass=hard_pass,
            wcag_contrast_score=float(data.get("wcag_contrast_score", 0.0)),
            overflow_0px_pass=overflow_pass,
            aesthetic_quality_score=float(data.get("aesthetic_quality_score", 0.0)),
            slop_penalty_deductions=float(data.get("slop_penalty_deductions", 0.0)),
            correction_advice=list(data.get("correction_advice", [])),
            iteration=int(data.get("iteration", 1)),
            acceptance_status=acceptance_status,
            detailed_checks=list(data.get("detailed_checks", [])),
            wcag_contrast_status=str(data.get("wcag_contrast_status", "NOT_EVALUATED")).upper(),
            overflow_status=str(data.get("overflow_status", "NOT_EVALUATED")).upper(),
            screenshot_status=str(data.get("screenshot_status", "NOT_EVALUATED")).upper(),
            critic_status=str(data.get("critic_status", "NOT_EVALUATED")).upper(),
            runtime_mode=str(data.get("runtime_mode", "static"))
        )

    def to_json(self, indent: int = 2) -> str:
        return json.dumps(self.to_dict(), ensure_ascii=False, indent=indent)

    @classmethod
    def from_json(cls, json_str: str) -> "EvaluationReportContract":
        return cls.from_dict(json.loads(json_str))
