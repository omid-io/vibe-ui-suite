    def validate(self) -> Tuple[bool, List[str]]:
        errors = []
        if not self.code_html_or_tsx or not isinstance(self.code_html_or_tsx, str):
            errors.append("code_html_or_tsx must contain executable markup or code")
        if not self.title or not isinstance(self.title, str):
            errors.append("title must be specified")
        if not isinstance(self.signature_widgets, (list, tuple)):
            errors.append("signature_widgets must be a list of widget specifications")
